class ControllableMockLLM(LLMProvider):
    def __init__(self, name: str, models: list[str], should_fail: bool = False, tokens: int = 150):
        self._name = name
        self._models = models
        self._should_fail = should_fail
        self._tokens = tokens
        self.health_check_called_count = 0
        self._capabilities = [ModelCapability.REASONING]

    @property
    def name(self) -> str:
        return self._name

    @property
    def models(self) -> list[str]:
        return self._models

    @property
    def is_local(self) -> bool:
        return True

    @property
    def capabilities(self) -> list[ModelCapability]:
        return self._capabilities

    async def complete(self, request: LLMRequest) -> LLMResponse:
        if self._should_fail:
            raise ProviderError(self.name, "Connection timed out")

        prompt_tok = self._tokens // 2
        comp_tok = self._tokens - prompt_tok
        return LLMResponse(
            content=f"Generated by {self.name}",
            model=request.model or self._models[0],
            usage={"prompt_tokens": prompt_tok, "completion_tokens": comp_tok, "total_tokens": self._tokens},
        )

    async def stream_complete(self, request: LLMRequest):
        yield "token"

    async def health_check(self) -> ProviderHealth:
        self.health_check_called_count += 1
        return ProviderHealth(provider=self.name, healthy=not self._should_fail)


@pytest_asyncio.fixture
async def db_session_maker():
    engine = create_async_engine("sqlite+aiosqlite:///:memory:", echo=False)
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    session_maker = async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)

    @asynccontextmanager
    async def session_factory():
        async with session_maker() as session:
            try:
                yield session
                await session.commit()
            except Exception:
                await session.rollback()
                raise

    yield session_factory, session_maker
    await engine.dispose()


@pytest.mark.asyncio
async def test_usage_semantics_single_success_one_record_and_accurate_cost(db_session_maker):
    session_factory, session_maker = db_session_maker

    # Create user
    async with session_maker() as session:
        user = DBUser(username="test_user", email="user@example.com", password_hash="hash")
        await UserRepository(session).create(user)
        await session.commit()
        user_id = user.id

    model_reg = ModelRegistry()
    model_reg.register(
        ModelDefinition(
            model_id="gpt-custom",
            provider_name="custom-prov",
            capabilities={ModelCapability.REASONING},
            input_cost=0.005,   # $5 per 1M tokens = $0.005 per 1K tokens
            output_cost=0.015,  # $15 per 1M tokens = $0.015 per 1K tokens
            priority=10,
        )
    )

    prov_reg = ProviderRegistry()
    # Prompt tokens = 500, Completion tokens = 500
    prov_reg.register_llm(ControllableMockLLM("custom-prov", ["gpt-custom"], tokens=1000))

    router = ModelRouter(model_registry=model_reg, provider_registry=prov_reg)
    gateway = ModelGateway(
        router=router,
        model_registry=model_reg,
        provider_registry=prov_reg,
        session_factory=session_factory,
    )

    req = LLMRequest(
        messages=[{"role": "user", "content": "Hello"}],
        metadata={"user_id": str(user_id)},
    )
    resp = await gateway.complete(req)

    # Cost = (0.005 / 1000 * 500) + (0.015 / 1000 * 500) = 0.0025 + 0.0075 = 0.0100
    expected_cost = (0.005 / 1000 * 500) + (0.015 / 1000 * 500)
    assert abs(resp.metadata["cost_usd"] - expected_cost) < 1e-6

    # Verify exactly ONE UsageRecord exists in DB
    async with session_maker() as session:
        records = await UsageRepository(session).get_user_usage(user_id)
        assert len(records) == 1
        assert records[0].success is True
        assert records[0].total_tokens == 1000
        assert abs(records[0].cost_usd - expected_cost) < 1e-6


@pytest.mark.asyncio
async def test_usage_semantics_fallback_success_records_only_successful_model(db_session_maker):
    session_factory, session_maker = db_session_maker

    async with session_maker() as session:
        user = DBUser(username="fallback_user", email="fb@example.com", password_hash="hash")
        await UserRepository(session).create(user)
        await session.commit()
        user_id = user.id

    model_reg = ModelRegistry()
    model_reg.register(
        ModelDefinition(
            model_id="primary-failing-model",
            provider_name="failing-prov",
            capabilities={ModelCapability.REASONING},
            priority=20,
        )
    )
    model_reg.register(
        ModelDefinition(
            model_id="secondary-success-model",
            provider_name="success-prov",
            capabilities={ModelCapability.REASONING},
            priority=10,
        )
    )

    prov_reg = ProviderRegistry()
    prov_reg.register_llm(ControllableMockLLM("failing-prov", ["primary-failing-model"], should_fail=True))
    prov_reg.register_llm(ControllableMockLLM("success-prov", ["secondary-success-model"], should_fail=False))

    router = ModelRouter(model_registry=model_reg, provider_registry=prov_reg)
    gateway = ModelGateway(
        router=router,
        model_registry=model_reg,
        provider_registry=prov_reg,
        session_factory=session_factory,
    )

    req = LLMRequest(
        model="primary-failing-model",
        messages=[{"role": "user", "content": "Hello"}],
        metadata={"user_id": str(user_id)},
    )
    resp = await gateway.complete(req)

    assert resp.model == "secondary-success-model"
    assert resp.metadata["fallback_occurred"] is True

    # Check DB: Exactly ONE record for the successful fallback model, NO success record for failing provider
    async with session_maker() as session:
        records = await UsageRepository(session).get_user_usage(user_id)
        assert len(records) == 1
        assert records[0].model == "secondary-success-model"
        assert records[0].provider == "success-prov"
        assert records[0].success is True


