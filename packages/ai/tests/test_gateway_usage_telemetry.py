@pytest.mark.asyncio
async def test_db_persistence_failure_does_not_corrupt_or_fail_ai_response():
    # Broken session factory that raises exception
    @asynccontextmanager
    async def broken_session_factory():
        raise RuntimeError("Database connection pool exhausted")
        yield None

    model_reg = ModelRegistry()
    model_reg.register(ModelDefinition(model_id="resilient-m", provider_name="resilient-p", capabilities={ModelCapability.REASONING}))

    prov_reg = ProviderRegistry()
    prov_reg.register_llm(ControllableMockLLM("resilient-p", ["resilient-m"]))

    router = ModelRouter(model_registry=model_reg, provider_registry=prov_reg)
    gateway = ModelGateway(
        router=router,
        model_registry=model_reg,
        provider_registry=prov_reg,
        session_factory=broken_session_factory,
    )

    req = LLMRequest(messages=[{"role": "user", "content": "Hi"}], metadata={"user_id": str(uuid4())})
    # Must NOT raise exception despite DB failure
    resp = await gateway.complete(req)
    assert resp.content == "Generated by resilient-p"


@pytest.mark.asyncio
async def test_health_cache_no_health_check_on_every_routing():
    model_reg = ModelRegistry()
    model_reg.register(
        ModelDefinition(
            model_id="m1",
            provider_name="p1",
            capabilities={ModelCapability.REASONING, ModelCapability.EXTRACTION, ModelCapability.SUMMARIZATION},
        )
    )

    prov_reg = ProviderRegistry()
    mock_prov = ControllableMockLLM("p1", ["m1"])
    prov_reg.register_llm(mock_prov)

    # Initial explicit health check caches health
    await prov_reg.health_check_all()
    assert mock_prov.health_check_called_count == 1

    router = ModelRouter(model_registry=model_reg, provider_registry=prov_reg)

    # Perform 10 routing decisions
    for _ in range(10):
        model_def, provider = router.select_model_and_provider(task="research")
        assert model_def.model_id == "m1"
        assert provider.name == "p1"

    # Health check count must remain 1 (no network calls during routing)
    assert mock_prov.health_check_called_count == 1
